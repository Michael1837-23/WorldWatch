#!/usr/bin/env python3
"""Generate compact Swift map data from Natural Earth 1:110m GeoJSON (public domain)."""
import argparse
import json
from pathlib import Path


def simplify(points, tolerance=0.25):
    def segment(points):
        if len(points) < 3:
            return points
        ax, ay = points[0]
        bx, by = points[-1]
        dx, dy = bx - ax, by - ay
        length = dx * dx + dy * dy
        distances = []
        for x, y in points[1:-1]:
            t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / length)) if length else 0
            distances.append((x - ax - t * dx) ** 2 + (y - ay - t * dy) ** 2)
        i = max(range(len(distances)), key=distances.__getitem__) + 1
        if distances[i - 1] <= tolerance * tolerance:
            return [points[0], points[-1]]
        return segment(points[:i + 1])[:-1] + segment(points[i:])

    ring = points[:-1] if points[0] == points[-1] else points
    split = max(range(1, len(ring)), key=lambda i: sum((a - b) ** 2 for a, b in zip(ring[i], ring[0])))
    reduced = segment(ring[:split + 1])[:-1] + segment(ring[split:] + [ring[0]])
    return reduced if len(reduced) >= 4 else points


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('geojson', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    rows = []
    for feature in json.loads(args.geojson.read_text())['features']:
        p, g = feature['properties'], feature['geometry']
        code = p['ISO_A3'] if p['ISO_A3'] != '-99' else p['ADM0_A3']
        polygons = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        rings = []
        for polygon in polygons:
            for ring in polygon:
                quantized = [(round(x * 10), round(y * 10)) for x, y in simplify(ring)]
                quantized = [v for i, v in enumerate(quantized) if i == 0 or v != quantized[i - 1]]
                if len(set(quantized)) >= 3:
                    rings.append(','.join(str(n) for pair in quantized for n in pair))
        fields = [code, p.get('NAME_EN') or p['NAME'], p['CONTINENT'], str(p['LABELRANK']),
                  str(round(p['LABEL_X'] * 10)), str(round(p['LABEL_Y'] * 10)), ';'.join(rings)]
        rows.append('|'.join(fields))
    source = '// Natural Earth 1:110m Admin 0 Countries — public domain. Generated by Tools/build_world_map.py.\n'
    source += 'enum WorldMapData {\n    static let encoded = #"""\n' + '\n'.join(rows) + '\n"""#\n}\n'
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source)
    assert args.output.stat().st_size <= 400_000
    print(f'{len(rows)} countries; {args.output.stat().st_size:,} bytes')


if __name__ == '__main__':
    main()
